import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";

import { COLORS } from "../src/mobile/theme";
import { isSharedAsset } from "../worker/kitchen";

const read = (path: string): string => readFileSync(path, "utf8");

/**
 * The phone app shipped every icon as the unmodified create-expo-app template artwork until
 * 2026-11-02, and `app.json` carried the template's pale blue (#E6F4FE) as the Android icon
 * background. Nothing failed: a wrong picture is not a type error, expo-doctor passed 20 of
 * 20 checks, and the suite was green. It was found by reading the pixels on the way to a
 * build, which is luck rather than a process.
 *
 * So the icons are GENERATED by scripts/app-icons.py from the mark in public/favicon.svg,
 * exactly as the link-preview card is, and these two checks hold the part a generator cannot:
 * that nobody reintroduces a colour from outside the palette, and that the one asset the App
 * Store rejects late is the shape it demands.
 */
describe("the app icons", () => {
  it("uses no colour that is not a DESIGN.md token", () => {
    const tokens = new Set(Object.values(COLORS).map((hex) => hex.toLowerCase()));
    const found = [...read("mobile/app.json").matchAll(/"#([0-9a-fA-F]{3,8})"/g)].map(
      (match) => `#${match[1].toLowerCase()}`,
    );
    // Not "there is at least one": a config that stopped naming colours entirely would pass
    // that and tell us nothing.
    expect(found.length).toBeGreaterThan(0);
    expect(found.filter((hex) => !tokens.has(hex))).toEqual([]);
  });

  it("gives the web a raster touch icon, since an SVG favicon is not used for a bookmark", () => {
    // Without this file, iOS saves a SCREENSHOT OF THE PAGE as the home-screen icon. It is
    // linked from index.html and kitchen.html, and worker/kitchen.test.ts checks the kitchen
    // host will actually serve it, which an anchored allowlist does not do by default.
    const png = readFileSync("public/apple-touch-icon.png");
    expect(png.readUInt32BE(16)).toBe(180);
    expect(png.readUInt8(25)).toBe(2);
    for (const file of ["index.html", "kitchen.html"]) {
      expect(read(file)).toContain('rel="apple-touch-icon"');
    }
  });

  it("serves every absolute asset kitchen.html actually asks for", () => {
    // SHARED_ASSET in worker/kitchen.ts is an anchored allowlist, so a file added to
    // kitchen.html and NOT added there is simply 404 on the kitchen host while every other
    // test passes: the list only ever knew the files someone remembered to type into it, and
    // its comment asked people to remember. This derives the question from the document.
    //
    // It lives HERE rather than beside the worker's own tests because worker/tsconfig has no
    // node types, on purpose: the worker runs on Cloudflare and must not reach for node APIs.
    // Reading a file from a test there compiles under vitest and fails `tsc -b`, which is how
    // this guard was first written.
    const html = read("kitchen.html");
    const referenced = [...html.matchAll(/(?:href|src)="(\/[^"]*)"/g)]
      .map((match) => match[1])
      // Only files. The shell itself and in-app routes are rewritten on purpose, not served.
      .filter((path) => /\.[a-z0-9]+$/i.test(path))
      // Vite replaces the source module entry with the hashed bundle at build, so
      // /src/kitchen/main.tsx never reaches a browser and must not be allowlisted: the built
      // /assets/kitchen-<hash>.js that takes its place already is.
      .filter((path) => !path.startsWith("/src/"));
    expect(referenced.length).toBeGreaterThan(0);
    expect(referenced.filter((path) => !isSharedAsset(path))).toEqual([]);
  });

  it("gives iOS an app icon with no alpha channel, which the store rejects after upload", () => {
    // A PNG's IHDR is the first chunk and its layout is fixed: width and height at bytes 16
    // and 20, colour type at byte 25. Type 2 is RGB; 6 is RGBA, which App Store Connect
    // refuses, hours after a build has finished.
    const png = readFileSync("mobile/assets/icon.png");
    expect(png.readUInt32BE(16)).toBe(1024);
    expect(png.readUInt32BE(20)).toBe(1024);
    expect(png.readUInt8(25)).toBe(2);
  });
});
